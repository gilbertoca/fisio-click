-- Módulo de segurança (alinhado ao padrão do V1: PK IDENTITY BY DEFAULT,
-- junções com PK composta). "BY DEFAULT" permite os IDs explícitos do seed
-- (V6) e, depois, IDs gerados pelo banco nas inclusões de tela.

CREATE TABLE fisio.papel (
    papel_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome      VARCHAR(150)  NOT NULL,
    descricao VARCHAR(400)
);
ALTER TABLE fisio.papel ADD CONSTRAINT papel_nome_key UNIQUE (nome);

CREATE TABLE fisio.permissao (
    permissao_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome         VARCHAR(150)  NOT NULL
);
ALTER TABLE fisio.permissao ADD CONSTRAINT permissao_nome_key UNIQUE (nome);

-- Junção papel↔permissão: PK composta no padrão sessao_procedimento (V1).
CREATE TABLE fisio.permissao_papel (
    papel_id     INT NOT NULL REFERENCES fisio.papel(papel_id),
    permissao_id INT NOT NULL REFERENCES fisio.permissao(permissao_id),
    CONSTRAINT pk_permissao_papel PRIMARY KEY (papel_id, permissao_id)
);

CREATE TABLE fisio.usuario (
    usuario_id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome            VARCHAR(200)   NOT NULL,
    username        VARCHAR(50)    NOT NULL,
    email           VARCHAR(150)   NOT NULL,
    senha           VARCHAR(1500)  NOT NULL, -- PBKDF2WithHmacSHA256 (hex)
    salt            VARCHAR(1500)  NOT NULL, -- salt aleatório (hex)
    ativo           BOOLEAN        NOT NULL DEFAULT TRUE,
    -- Vínculo opcional com o profissional: o usuário clínico pode amarrar a
    -- própria conta à ficha dele (painel/agenda); o administrador não tem.
    profissional_id INT            REFERENCES fisio.profissional(profissional_id)
);
ALTER TABLE fisio.usuario ADD CONSTRAINT usuario_username_key UNIQUE (username);

-- Junção usuário↔papel: PK composta, um usuário pode acumular papéis.
CREATE TABLE fisio.usuario_papel (
    usuario_id INT NOT NULL REFERENCES fisio.usuario(usuario_id),
    papel_id   INT NOT NULL REFERENCES fisio.papel(papel_id),
    CONSTRAINT pk_usuario_papel PRIMARY KEY (usuario_id, papel_id)
);
