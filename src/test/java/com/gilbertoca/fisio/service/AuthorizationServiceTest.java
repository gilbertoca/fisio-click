package com.gilbertoca.fisio.service;

import static org.junit.Assert.*;

import com.gilbertoca.fisio.infra.DataSourceManager;
import com.gilbertoca.fisio.model.Usuario;
import org.junit.AfterClass;
import org.junit.BeforeClass;
import org.junit.Test;
import org.sql2o.Connection;

/**
 * Autorização: matriz de wildcards (estática, sem banco) e as permissões
 * efetivas contra o banco de migrações — admin semente do V6 (*), Operador
 * semeado neste teste (papel 3) e usuário sem papel nenhum.
 */
public class AuthorizationServiceTest {

    private static AuthorizationService authorizationService;
    private static Usuario operador;       // papel 3: recepção, sem excluir
    private static Usuario semPapel;       // autenticado, mas sem permissões
    private static Usuario admin;          // semente do V6: *

    @BeforeClass
    public static void setUp() {
        String jdbcUrl = "jdbc:h2:mem:fisio_authz_test;MODE=PostgreSQL;DB_CLOSE_DELAY=-1;INIT=CREATE SCHEMA IF NOT EXISTS FISIO;DATABASE_TO_LOWER=TRUE";
        DataSourceManager.initialize(jdbcUrl, "sa", "", "org.h2.Driver");
        DataSourceManager.runMigrations();
        authorizationService = new AuthorizationService();
        seedUsuarios();
    }

    @AfterClass
    public static void tearDown() {
        DataSourceManager.shutdown();
    }

    /** Operador (papel 3) e usuário sem papel — credenciais irrelevantes:
     * a autorização parte do objeto na sessão, não da senha. O admin
     * semente ocupa o id 1 (V6), então os ids são explícitos: com
     * GENERATED BY DEFAULT, insert explícito não avança a sequência. */
    private static void seedUsuarios() {
        try (Connection conn = DataSourceManager.getSql2o().beginTransaction()) {
            conn.createQuery(
                    "INSERT INTO fisio.usuario (usuario_id, nome, username, email, senha, salt, ativo) "
                    + "VALUES (2, 'Operador Teste', 'operador', 'operador@teste.com', 'x', 'y', TRUE)")
                    .executeUpdate();
            conn.createQuery("INSERT INTO fisio.usuario_papel (usuario_id, papel_id) VALUES (2, 3)")
                    .executeUpdate();

            conn.createQuery(
                    "INSERT INTO fisio.usuario (usuario_id, nome, username, email, senha, salt, ativo) "
                    + "VALUES (3, 'Sem Papel Teste', 'sempapel', 'sempapel@teste.com', 'x', 'y', TRUE)")
                    .executeUpdate();

            conn.commit();

            operador = new Usuario();
            operador.setId(2);
            operador.setUsername("operador");
            semPapel = new Usuario();
            semPapel.setId(3);
            semPapel.setUsername("sempapel");
            admin = new Usuario();
            admin.setId(1); // semente do V6
            admin.setUsername("admin");
        }
    }

    // ---- Matriz de wildcards (pura, sem banco) -----------------------------

    @Test
    public void curingaUniversalConcedeTudo() {
        assertTrue(AuthorizationService.casa("*", "cliente:excluir"));
        assertTrue(AuthorizationService.casa("*", "faturamento:importar"));
        assertTrue(AuthorizationService.casa("*", "*"));
    }

    @Test
    public void curingaDeModuloConcedeSoODele() {
        assertTrue("sessao:* deve cobrir toda ação da sessão.",
                AuthorizationService.casa("sessao:*", "sessao:atender"));
        assertTrue(AuthorizationService.casa("sessao:*", "sessao:visualizar"));
        assertFalse("sessao:* NÃO deve vazar para outro módulo.",
                AuthorizationService.casa("sessao:*", "cliente:excluir"));
    }

    @Test
    public void permissaoExataCasaSoConsigoMesma() {
        assertTrue(AuthorizationService.casa("cliente:editar", "cliente:editar"));
        assertFalse("Permissão exata não deve cobrir irmãs.",
                AuthorizationService.casa("cliente:editar", "cliente:excluir"));
    }

    @Test
    public void entradasNulasNaoConcedemNada() {
        assertFalse(AuthorizationService.casa(null, "cliente:editar"));
        assertFalse(AuthorizationService.casa("cliente:editar", null));
        assertFalse(AuthorizationService.casa(null, null));
    }

    // ---- Permissões efetivas contra o banco -------------------------------

    @Test
    public void adminComCuringaUniversalTemTudo() {
        assertTrue(authorizationService.temPermissao(admin, "cliente:excluir"));
        assertTrue(authorizationService.temPermissao(admin, "profissional:visualizar"));
        assertTrue(authorizationService.temPermissao(admin, "usuario:adicionar"));
    }

    @Test
    public void operadorTemCadastrosEAagendaMasNaoExcluir() {
        assertTrue("Operador edita cadastros.",
                authorizationService.temPermissao(operador, "cliente:editar"));
        assertTrue("Operador atende a agenda (atender).",
                authorizationService.temPermissao(operador, "sessao:atender"));
        assertFalse("Operador NÃO exclui — a ação é de administrador/gerente.",
                authorizationService.temPermissao(operador, "cliente:excluir"));
        assertFalse("Operador NÃO vê profissionais.",
                authorizationService.temPermissao(operador, "profissional:visualizar"));
    }

    @Test
    public void usuarioSemPapelNaoTemNada() {
        assertFalse("Sem papel, nenhuma permissão é herdada.",
                authorizationService.temPermissao(semPapel, "cliente:visualizar"));
        assertFalse(authorizationService.temPermissao(semPapel, "sessao:atender"));
    }

    @Test
    public void usuarioNuloNaoTemNada() {
        assertFalse(authorizationService.temPermissao(null, "cliente:visualizar"));
    }
}
